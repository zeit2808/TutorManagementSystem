using System.Globalization;
using System.Text.RegularExpressions;

namespace TutorManagement.SharedKernel.Primitives;

/// <summary>
/// One family of automatic codes inside a center, named by its prefix (HS, GV, LH…). Each module declares the
/// kinds it owns; the prefix is also the counter key, so two kinds must never share one.
/// </summary>
public sealed partial record CodeKind
{
    public CodeKind(string prefix)
    {
        if (!PrefixPattern().IsMatch(prefix))
            throw new ArgumentException("A code prefix is 2–4 upper-case letters.", nameof(prefix));
        Prefix = prefix;
    }

    public string Prefix { get; }

    [GeneratedRegex("^[A-Z]{2,4}$")]
    private static partial Regex PrefixPattern();
}

/// <summary>
/// Decision D9, extended to every catalog: codes are generated by the server per center as PREFIX-000001,
/// PREFIX-000002… Users never type them, so they are always valid and unique.
/// </summary>
public static class EntityCode
{
    public static string Format(CodeKind kind, long number)
    {
        ArgumentNullException.ThrowIfNull(kind);
        ArgumentOutOfRangeException.ThrowIfNegativeOrZero(number);
        return kind.Prefix + "-" + number.ToString("D6", CultureInfo.InvariantCulture);
    }
}
